/** submit_result evaluation: pure logic, unit-testable without an agent loop. */

import { ArkErrors, type Type } from "arktype";

/** A director's declared shape for submit_result's payload. */
export type OutputType = Type<unknown>;

export const SUBMIT_RESULT_MAX_CORRECTIONS = 3;

export interface SubmitResultState {
  corrections: number;
}

export function createSubmitResultState(): SubmitResultState {
  return { corrections: 0 };
}

/** Steering rotates the turn: drop the correction count so the new token gets a full budget. */
export function resetSubmitResultTurn(state: SubmitResultState): void {
  state.corrections = 0;
}

export interface SubmitResultInput {
  /** This turn's token, generated by runSubAgent at dispatch time. */
  turnToken: string;
  /** The turn_token argument the worker actually passed. */
  submittedToken: unknown;
  /** The result argument the worker passed. */
  result: unknown;
  /** Declared output shape, if the director's report contract has one. */
  outputType?: OutputType;
  state: SubmitResultState;
  maxCorrections?: number;
}

/** Invalid submissions return `ok: false` so the worker can retry, not a thrown error. */
export function evaluateSubmitResult(input: SubmitResultInput): {
  ok: boolean;
  message: string;
} {
  const cap = input.maxCorrections ?? SUBMIT_RESULT_MAX_CORRECTIONS;
  if (
    typeof input.submittedToken !== "string" ||
    input.submittedToken !== input.turnToken
  ) {
    return {
      ok: false,
      message:
        "Error: turn_token does not match this turn — this dispatch was superseded.",
    };
  }
  if (input.state.corrections >= cap) {
    return {
      ok: false,
      message: `Error: submit_result correction cap (${cap}) reached for this turn. No further attempts accepted — finish with the markdown report envelope instead.`,
    };
  }
  if (input.outputType !== undefined) {
    const checked = input.outputType(input.result);
    if (checked instanceof ArkErrors) {
      input.state.corrections += 1;
      return {
        ok: false,
        message: [
          `Invalid submission (${input.state.corrections}/${cap} corrections used):`,
          checked.summary,
          "Fix and call submit_result again with the same turn_token.",
        ].join("\n"),
      };
    }
  }
  return { ok: true, message: "Result accepted." };
}
